"""Builds data/garrison_routes.json: each round's enemy routes per map, for the in-game route overlay.

Input: LBEILC/StrongholdAssistant data/garrison_routes.json (Apache-2.0), itself generated by its
scripts/generate-garrison-routes.mjs from Kengxxiao/ArknightsGameData zh_CN (act3autochess V3_1 levels and
activity_table). This script only renames the maps to this project's ids, adds the HUD mode names and drops the
generator's debug snaps.

    python data/build_garrison_routes.py <StrongholdAssistant garrison_routes.json> <activity_table.json>
"""
import json
import os
import sys

# StrongholdAssistant's level map ids → ours (matched by identical board fingerprints).
MAP_IDS = {
    "m01": "desert_crates", "m02": "desert_cactus", "m03": "desert_steel", "m04": "desert_laser",
    "m05": "city", "m06": "desert_camo", "m09": "snow", "m10": "palace", "m11": "snow_ice", "m12": "palace_arrows",
}


# Paths the generator got wrong (it takes the shortest walk; the game's enemies go another way), checked in game:
# map id → [(points as generated, points as walked)], cell centres (col + .5, row + .5).
ROUTE_FIXES = {
    # 沙漠（双仙人掌）上路: along the top row to column 0, then down — not through column 3.
    "desert_cactus": [([(4.5, 0.5), (3.5, 1.5), (3.5, 3.5)], [(0.5, 0.5), (0.5, 3.5)])],
    # 宫殿上路: along the top row to column 1, then down — not through column 3.
    "palace": [([(4.5, 0.5), (3.5, 1.5), (3.5, 3.5)], [(1.5, 0.5), (1.5, 3.5)])],
    # 雪原（隐匿格）上路: along the top row to column 0, then down — not through column 2.
    "snow": [([(3.5, 0.5), (2.5, 1.5), (2.5, 3.5)], [(0.5, 0.5), (0.5, 3.5)])],
}


def fix_routes(maps: dict) -> int:
    """Applies ROUTE_FIXES to every walking segment in place (dropping repeated points); returns how many changed."""
    changed = 0
    for map_id, fixes in ROUTE_FIXES.items():
        for level in maps.get(map_id, {}).get("levels", {}).values():
            for route in level["routes"]:
                if route["motion"] != "walk":
                    continue
                for i, seg in enumerate(route["segments"]):
                    pts = [(p["col"], p["row"]) for p in seg]
                    for old, new in fixes:
                        k = 0
                        while k + len(old) <= len(pts):
                            if pts[k:k + len(old)] == old:
                                pts[k:k + len(old)] = new
                                k += len(new)
                                changed += 1
                            else:
                                k += 1
                    pts = [p for j, p in enumerate(pts) if j == 0 or p != pts[j - 1]]
                    route["segments"][i] = [{"col": c, "row": r} for c, r in pts]
    return changed


def main(src, activity):
    data = json.load(open(src, encoding="utf-8"))
    act = json.load(open(activity, encoding="utf-8"))
    modes = act["activity"]["AUTOCHESS"]["act3autochess"]["V3_1"]["modeDataDict"]
    out = {
        "_notice": "Enemy routes per round, converted from LBEILC/StrongholdAssistant data/garrison_routes.json "
                   "(Apache-2.0), generated from Kengxxiao/ArknightsGameData zh_CN act3autochess V3_1; see NOTICE. "
                   "Points are cell centres (col+0.5, row+0.5) on the deployment grid of garrison_maps.json.",
        "modes": {m["name"]: {"id": m["modeId"], "solo": m["modeType"] != "MULTI"}
                  for m in modes.values() if m["modeType"] != "LOCAL"},
        "battles": data["battles"],
        "bossIds": data["bossIds"],
        "maps": {MAP_IDS[k]: v for k, v in data["maps"].items()},
    }
    fix_routes(out["maps"])
    missing = set(data["maps"]) - set(MAP_IDS)
    if missing:
        raise SystemExit(f"unmapped maps: {sorted(missing)}")
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "garrison_routes.json")
    with open(path, "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, separators=(",", ":"))
    print(path, len(out["modes"]), "modes,", len(out["maps"]), "maps")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
